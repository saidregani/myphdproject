import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
from matplotlib.patches import Arc, FancyArrowPatch
fig,ax=plt.subplots(1,2,figsize=(12,4.8),gridspec_kw={'width_ratios':[1.45,1]})
# --- caractéristique
a=ax[0]; p=np.linspace(-np.pi,np.pi,600)
a.axvspan(0,np.pi,color='tab:green',alpha=.08); a.axvspan(-np.pi,0,color='tab:red',alpha=.08)
a.axvspan(-np.pi/2,np.pi/2,ymin=0,ymax=0.06,color='tab:blue',alpha=.35)
a.plot(p,np.sin(p),'tab:blue',lw=2.2,label=r'$\varepsilon/V_m=\sin\psi$')
pl=np.linspace(-1.0,1.0,10); a.plot(pl,pl,'k--',lw=1.2,label=r'approx. linéaire $\varepsilon/V_m\approx\psi$')
a.axhline(0,color='k',lw=.6); a.axvline(0,color='k',lw=.6)
a.plot(0,0,'o',ms=11,color='tab:green',mec='k',zorder=5)
for x in (-np.pi,np.pi): a.plot(x,0,'o',ms=11,mfc='white',mec='tab:red',mew=2.5,zorder=5)
a.annotate('$\\psi=0$ : équilibre STABLE\n(PLL verrouillée)',(0,0),(0.45,-0.6),fontsize=9,arrowprops=dict(arrowstyle='->'))
a.annotate('$\\psi=\\pi$ : équilibre\nINSTABLE',(np.pi,0),(2.0,-0.75),fontsize=9,arrowprops=dict(arrowstyle='->'))
a.text(1.8,0.3,r'$\psi>0 \Rightarrow \varepsilon>0$'+'\n'+r'$\hat\theta$ EN RETARD',ha='center',fontsize=9,color='darkgreen')
a.text(-1.8,-0.35,r'$\psi<0 \Rightarrow \varepsilon<0$'+'\n'+r'$\hat\theta$ EN AVANCE',ha='center',fontsize=9,color='darkred')
a.text(0,-1.48,r'zone $|\psi|<\pi/2$ : pente $\cos\psi>0$ (zone de la preuve)',ha='center',fontsize=8.5,color='tab:blue')
a.set_xticks([-np.pi,-np.pi/2,0,np.pi/2,np.pi]); a.set_xticklabels([r'$-\pi$',r'$-\pi/2$','0',r'$\pi/2$',r'$\pi$'])
a.set_xlabel(r'erreur de phase $\psi=\theta-\hat\theta$ (rad)'); a.set_ylabel(r'$\varepsilon/V_m$')
a.set_ylim(-1.75,1.5); a.set_xlim(-np.pi-.15,np.pi+.15); a.legend(loc='upper left',fontsize=8.5); a.grid(alpha=.25)
a.set_title('(a) Caractéristique du détecteur de phase')
# --- phaseurs
b=ax[1]; th=np.deg2rad(65); thh=np.deg2rad(35); R=1
b.add_patch(plt.Circle((0,0),R,fill=False,ls=':',color='gray'))
b.arrow(-1.25,0,2.5,0,head_width=.03,color='gray'); b.arrow(0,-.3,0,1.55,head_width=.03,color='gray')
b.text(1.27,-.07,r'$\alpha$'); b.text(.03,1.25,r'$\beta$')
V=R*np.array([np.cos(th),np.sin(th)])
b.annotate('',V,(0,0),arrowprops=dict(arrowstyle='-|>',lw=2.5,color='tab:blue'))
b.text(V[0]+.03,V[1]+.03,r'$\vec V$ (angle réel $\theta$)',color='tab:blue',fontsize=9)
d=np.array([np.cos(thh),np.sin(thh)]); q=np.array([-np.sin(thh),np.cos(thh)])
b.plot([0,1.2*d[0]],[0,1.2*d[1]],color='tab:orange',lw=1.8); b.text(1.2*d[0]+.02,1.2*d[1],r'axe $d$ (angle $\hat\theta$)',color='tab:orange',fontsize=9)
b.plot([0,.75*q[0]],[0,.75*q[1]],color='tab:purple',lw=1.8); b.text(.75*q[0]-.25,.75*q[1]+.04,r'axe $q$',color='tab:purple',fontsize=9)
pd_=(V@d)*d; pq=(V@q)*q
b.plot([V[0],pd_[0]],[V[1],pd_[1]],'k:',lw=1)
b.annotate('',pq,(0,0),arrowprops=dict(arrowstyle='-|>',lw=2.5,color='tab:red'))
b.text(pq[0]-.62,pq[1]-.12,r'$\varepsilon=V_q=V_m\sin\psi$',color='tab:red',fontsize=9.5)
b.annotate('',pd_,(0,0),arrowprops=dict(arrowstyle='-|>',lw=2,color='tab:green'))
b.text(pd_[0]-.05,pd_[1]-.17,r'$V_d=V_m\cos\psi$',color='tab:green',fontsize=9)
b.add_patch(Arc((0,0),.6,.6,theta1=np.rad2deg(thh),theta2=np.rad2deg(th),color='k',lw=1.4))
b.text(.33*np.cos((th+thh)/2)+.02,.33*np.sin((th+thh)/2),r'$\psi$',fontsize=11)
b.add_patch(Arc((0,0),.3,.3,theta1=0,theta2=np.rad2deg(thh),color='tab:orange'))
b.text(.17,.04,r'$\hat\theta$',color='tab:orange',fontsize=9)
b.set_aspect('equal'); b.set_xlim(-1.3,1.45); b.set_ylim(-.35,1.35); b.axis('off')
b.set_title(r'(b) Projection de $\vec V$ sur les axes estimés')
fig.tight_layout(); fig.savefig('figures/detecteur_phase.pdf'); fig.savefig('figures/detecteur_phase.png',dpi=150)
